// Exports the final wireframe (docs/ui/final/wireframe-final.html) for the UI spec:
//   docs/ui/final/NN-<screen>.png   one 1280x720 image per screen
//   docs/ui/final/layout.json       every element's design rect, font size and anchor
//   docs/ui/UI_SPEC.md              the "Screen specs" tables between the BEGIN/END markers
// Usage: node docs/ui/final/build.mjs   (headless Chrome, no dev server needed)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { launchBrowser } from '../../../tools/browser.mjs';
import { EN, SCREENS_EN } from './names-en.mjs';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const SPEC = path.join(DIR, '..', 'UI_SPEC.md');
const BEGIN = '<!-- BEGIN SCREEN SPECS (generated by docs/ui/final/build.mjs) -->';
const END = '<!-- END SCREEN SPECS -->';

const browser = await launchBrowser({ defaultViewport: { width: 1280, height: 720 } });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(pathToFileURL(path.join(DIR, 'wireframe-final.html')).href + '?export');
if (errors.length) throw new Error(errors.join('\n'));
const screens = await page.evaluate(() => globalThis.FINAL);
const bad = await page.evaluate(() => [...document.querySelectorAll('.check.bad')].map((c) => c.textContent));
if (bad.length) throw new Error('elements missing / added:\n' + bad.join('\n'));
for (const frame of await page.$$('.frame[data-file]')) {
  const file = await frame.evaluate((f) => f.dataset.file);
  await frame.screenshot({ path: path.join(DIR, file) });
}
await browser.close();
fs.writeFileSync(path.join(DIR, 'layout.json'), JSON.stringify({ canvas: [1280, 720], screens }, null, 1));

// ---------------------------------------------------------------- the spec tables
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
let md = `${BEGIN}\n`;
for (const s of screens) {
  md += `\n### ${s.sid} ${SCREENS_EN[s.sid]}\n\nImage: \`docs/ui/final/${s.file}\` (${s.concept === 'reference' ? "the user's reference image" : `concept ${s.concept}`}).\n\n`;
  md += '| id | Element | Original object | Anchor | x | y | w | h | Font | Notes |\n|---|---|---|---|---|---|---|---|---|---|\n';
  for (const e of s.els) {
    const en = EN[e.id];
    if (!en) throw new Error(`no English name for ${e.id} (docs/ui/final/names-en.mjs)`);
    const [name, object] = Array.isArray(en) ? en : [en, e.object];
    const notes = [e.state ? 'state (shown only when it applies)' : '', e.request ? 'added on request' : ''].filter(Boolean).join('; ');
    md += `| \`${e.id}\` | ${cell(name)} | \`${cell(object)}\` | ${e.anchor} | ${e.x} | ${e.y} | ${e.w} | ${e.h} | ${e.fs ?? ''} | ${notes} |\n`;
  }
}
md += `\n${END}`;
if (fs.existsSync(SPEC)) {
  const spec = fs.readFileSync(SPEC, 'utf8');
  const a = spec.indexOf(BEGIN);
  const b = spec.indexOf(END);
  if (a < 0 || b < 0) throw new Error('UI_SPEC.md has no screen spec markers');
  fs.writeFileSync(SPEC, spec.slice(0, a) + md + spec.slice(b + END.length));
}
console.log(`${screens.length} screens -> PNG + layout.json${fs.existsSync(SPEC) ? ' + UI_SPEC.md' : ''}`);

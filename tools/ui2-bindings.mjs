const scenes = {};
function scene(name, ids, frames = {}) {
  const json = JSON.parse(fs.readFileSync(`public/assets/prefabs/Scenes/${name}.json`, 'utf8'));
  const path = i => json.nodes[i].p == null ? json.nodes[i].n : path(json.nodes[i].p) + '/' + json.nodes[i].n;
  scenes[name] = { bindings: Object.entries(ids).map(([i,id])=>({path:path(+i), id})), frames: Object.entries(frames).map(([i,rect])=>({path:path(+i), rect})) };
}

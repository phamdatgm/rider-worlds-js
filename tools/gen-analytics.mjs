import { readFileSync, writeFileSync } from 'node:fs';

const manifest = JSON.parse(readFileSync('public/assets/manifest.json', 'utf8'));
const meta = JSON.parse(readFileSync('public/assets/meta.json', 'utf8'));
const DIFFICULTIES = ['easy', 'moderate', 'difficult'];
const snake = (s) =>
  String(s ?? '')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();

// src/analytics/index.js levelOf(): the Endless worlds, then the timed levels in world / difficulty / number order
const timedOrder = (l) => (l.world * 10 + l.difficulty) * 100 + l.number;
const levels = [
  ...manifest.worlds.map((w) => ({ id: `endless_w${w.index + 1}`, index: w.index + 1, name: `Endless - World ${w.index + 1}` })),
  ...[...manifest.levels]
    .sort((a, b) => timedOrder(a) - timedOrder(b))
    .map((l, i) => ({ id: `w${l.world + 1}_${DIFFICULTIES[l.difficulty]}_${l.number}`, index: manifest.worlds.length + i + 1, name: l.name })),
];

const ITEM_TYPES = { 10000: 'vehicle', 20000: 'color', 30000: 'trail', 31000: 'explosion', 32000: 'landing', 40000: 'booster' };
const itemTypes = {};
for (const c of meta.cards) {
  const t = ITEM_TYPES[c.type];
  if (t) (itemTypes[t] ||= []).push(snake(c.name));
}


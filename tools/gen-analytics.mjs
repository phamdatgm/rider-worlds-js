  currencies: ['gems', 'rubies', 'bonus_letters', 'rank_stars'],
  sources: ['endless', 'timed_level', 'rank', 'bonus', 'ads', 'chests', 'daily_deals', 'challenges', 'card', 'cosmetic_level', 'player_star_collection', 'rv_reward_track', 'unknown'],
  sinks: ['endless', 'chests', 'daily_deals', 'challenges', 'bonus', 'unknown'],

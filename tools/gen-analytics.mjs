  screens: ['loading', 'game', 'pause', 'revive', 'home', 'shop', 'garage', 'settings', 'placeholder', 'levels', 'challenges', 'world_stats', 'bonus_claim', 'reward_track', 'rank_up', 'chest_open', 'no_ad', 'leaderboard'],
